pub fn system_is_thai() -> bool {
    sys_locale::get_locale()
        .map(|l| l.to_ascii_lowercase().starts_with("th"))
        .unwrap_or(false)
}

pub fn tr(lang: Language) -> &'static Tr {
    match lang {
        Language::English => &EN,
        Language::Thai => &TH,
        Language::Auto => {
            if system_is_thai() {
                &TH
            } else {
                &EN
            }
        }
    }
}
